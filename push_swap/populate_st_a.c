#include "push_swap.h"

void	populate_st_a(int **pos_st_a, int n)
{
	int	i;

	if (n > 0)
	{
		i = 0;
		while (i <= (n / 2))
		{
			pos_st_a[0][i] = i;
			i++;
		}
		while (i < n)
		{
			pos_st_a[0][i] = -(n - i);
			i++;
		}
	}
}
